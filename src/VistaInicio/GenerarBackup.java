    private void BotonGenerarMousePressed(java.awt.event.MouseEvent evt) {
        String tipoAccion = (String) ComboBoxTiposdeReportes.getSelectedItem();
        BotonGenerar.setEnabled(false);
        
        SwingWorker<Void, Integer> worker = new SwingWorker<>() {
            @Override
            protected Void doInBackground() throws Exception {
                publish(10); // Inicializando
                Thread.sleep(500);
                
                publish(30); // Preparando comandos de DB
                BackupDB backup = new BackupDB(IDUSuario, Conexion, tipoAccion);
                
                publish(60); // Ejecutando Proceso (Backup/Restore)
                backup.Decision();
                
                publish(100); // Finalizado
                return null;
            }

            @Override
            protected void process(List<Integer> chunks) {
                int value = chunks.get(chunks.size() - 1);
                rSProgressBar1.setValue(value);
            }

            @Override
            protected void done() {
                try {
                    get();
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(GenerarBackup.this, "Error en la operación de DB: " + e.getMessage());
                } finally {
                    rSProgressBar1.setValue(0);
                    BotonGenerar.setEnabled(true);
                }
            }
        };
        
        worker.execute();
    }

