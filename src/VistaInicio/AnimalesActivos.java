    public void Mostrar () throws SQLException{
        
        // Obtener el valor actual del ComboBox
        String Tipa = (String) ComboBoxAnimales.getSelectedItem();
        
        String sql = "SELECT codigo, genero, ubicacion from animales where tipo_animal = ? and estado = ?;";
        PreparedStatement ps = Conexion.prepareStatement(sql);
        ps.setString(1, Tipa);
        ps.setString(2, "1");
         
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn ("Codigo");
        model.addColumn ("Genero");
        model.addColumn ("Ubicacion");
        TablaAnimales.setModel (model);
        
        String [] datos = new String[3];

        try{
            
            ResultSet rs = ps.executeQuery();
            while(rs.next())
            {
                datos[0] = rs.getString(1);
                datos[1] = rs.getString(2);
                datos[2] = rs.getString(3);
                model.addRow(datos);
            }
        }catch(SQLException e){
            JOptionPane.showMessageDialog(null, "Error" + e.toString());
        }
    }

