    private void CampoRazonGastoMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_CampoRazonGastoMousePressed
        // TODO add your handling code here:
        // 1. Limpiar el campo de razón si tiene el texto por defecto
        if(CampoRazonGasto.getText().equals("Ej: Pago de Luz")){
            CampoRazonGasto.setText("");
            CampoRazonGasto.setForeground(Color.black);
        }

        // 2. Verificar si CampoValorGasto está vacío o no tiene número válido
        String textoValor = CampoValorGasto.getText();
        boolean tieneValorValido = false;

        try {
            ValorGasto = Integer.valueOf(textoValor);
            tieneValorValido = true; // Si llegó aquí, es válido
        } catch (NumberFormatException e) {
            // No es válido (vacío o texto no numérico)
            tieneValorValido = false;
        }

        // 3. Si no tiene valor válido, poner uno por defecto
        if(!tieneValorValido){
            CampoValorGasto.setText("Ej: 50000");
            CampoValorGasto.setForeground(new Color(204,204,204));
        }
    }//GEN-LAST:event_CampoRazonGastoMousePressed

    private void CampoValorGastoMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_CampoValorGastoMousePressed
       // TODO add your handling code here:
      // Verificar si CampoValorGasto está vacío o no tiene número válido
            String textoValor = CampoValorGasto.getText();
            boolean tieneValorValido = false;

            try {
                ValorGasto = Integer.valueOf(textoValor);
                tieneValorValido = true;
            } catch (NumberFormatException e) {
                // No es válido (vacío o texto no numérico)
                tieneValorValido = false;
                // ValorGasto se queda como null o con su valor anterior
            }

            // Verificar si CampoRazonGasto está vacío
            if(CampoRazonGasto.getText().isEmpty()){
                CampoRazonGasto.setText("Ej: Pago de Luz");
                CampoRazonGasto.setForeground(new Color(204,204,204));
            }

            // CORREGIDO: Verificar si el campo tiene el texto de ayuda
            // Deberías verificar el texto del campo, no el valor numérico
            if(CampoValorGasto.getText().equals("Ej: 50000")){
                CampoValorGasto.setText("");
                CampoValorGasto.setForeground(Color.black);
            }

    }//GEN-LAST:event_CampoValorGastoMousePressed

    private void BotonGastoMantenimientoMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_BotonGastoMantenimientoMousePressed
        // TODO add your handling code here:
        String textoValor = CampoValorGasto.getText();
        String RazonGasto = CampoRazonGasto.getText();
        boolean tieneValorValido = false;
        try {
            ValorGasto = Integer.valueOf(textoValor);
            tieneValorValido = true; // Si llegó aquí, es válido
        } catch (NumberFormatException e) {
            // No es válido (vacío o texto no numérico)
            tieneValorValido = false;
        }

        GastosDeMantenimiento Gastos = new GastosDeMantenimiento(IDUsuario, Conexion, RazonGasto,ValorGasto);
        try {
            Gastos.GastosDeMantenimiento();
        } catch (SQLException ex) {
            Logger.getLogger(GastosMantenimiento.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_BotonGastoMantenimientoMousePressed


