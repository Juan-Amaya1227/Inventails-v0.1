    private void BotonComprarAnimalMousePressed(java.awt.event.MouseEvent evt) {
        String animalSeleccionado = (String) ComboBoxAnimales.getSelectedItem();
        if (animalSeleccionado == null || animalSeleccionado.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Debe seleccionar un tipo de animal en la parte superior");
            return;
        }
        VistasInicio(new PanelCompras(Conexion, IDUsuario, animalSeleccionado, colaCompra, registros));
    }

