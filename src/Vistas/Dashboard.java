    private void BotonCerrarSesionMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_BotonCerrarSesionMousePressed
        // TODO add your handling code here:
        AuditoriaCierreSesion Auditoria = new AuditoriaCierreSesion(IDUsuario);
         try {
            Auditoria.RegistrarCierreSesion();
        } catch (SQLException ex) {
            Logger.getLogger(PanelAdministrativo.class.getName()).log(Level.SEVERE, null, ex);
        }
        JOptionPane.showMessageDialog(null, "Gracias por utilizar nuestros servicios, Hasta luego :)");
        this.dispose();
    }//GEN-LAST:event_BotonCerrarSesionMousePressed

