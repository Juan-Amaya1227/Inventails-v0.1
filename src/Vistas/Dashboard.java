    private void NivelUsuarioID(){
        
        // Modificamos la Gui segun el nivel de acceso del usuario
        
         if(nivelUsuario == 1){
         //Si el usuario es un Administracdor le habilitamos las opciones de generar Backups y restaurarlos ademas de generar los reportes
         TextoTransversal = "    Backup DB";
              TextoEspejo = "    Generar Reporte";
         }
         else if(nivelUsuario == 2){
        //Si el usuario es un Gestor le habilitamos unicamente que vea las transacciones recientes
         TextoTransversal = "    Transacciones";
         TextoEspejo = "";
         
         }
    
    }
    
