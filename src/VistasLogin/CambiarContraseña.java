    private void CampoContraseña1MousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_CampoContraseña1MousePressed
        String contra1 = new String(CampoContraseña1.getPassword());
        if (contra1.equals("123456")) {
            CampoContraseña1.setText("");
            CampoContraseña1.setForeground(Color.black);
        }
        String contra2 = new String(CampoContraseña2.getPassword());
        if (contra2.isEmpty()) {
            CampoContraseña2.setText("123456");
            CampoContraseña2.setForeground(new Color(204, 204, 204));
        }
    }//GEN-LAST:event_CampoContraseña1MousePressed

