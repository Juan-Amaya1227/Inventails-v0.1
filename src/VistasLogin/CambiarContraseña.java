     public void EjecutarCambioContraseña(){

        EditarContraseña EditarContraseña = new EditarContraseña(usuario, Contraseña1, Contraseña2, conexion);
        
        try {
            EditarContraseña.EjecutarMetodos();
        } catch (SQLException ex) {
            Logger.getLogger(CambiarContraseña.class.getName()).log(Level.SEVERE, null, ex);}
    
    }
    
