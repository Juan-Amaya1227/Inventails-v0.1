    private void validarLogin() throws SQLException, InterruptedException {
             usuario = CampoUsuario.getText();
             String contraseña = new String(CampoPassword.getPassword());

             // Verificar si el usuario está bloqueadowwewrewrerewrweweewewr<
             if(usuario.equals(UsuarioBloqueado)) {
                 JOptionPane.showMessageDialog(null, "Usuario: " + usuario + " está bloqueado temporalmente. Espere 3 minutos.", "Error", JOptionPane.ERROR_MESSAGE);
                 return;
             }

             // Consulta a la base de datos para validar credenciales
             String query = "SELECT id, password, nivelPermiso FROM usuarios WHERE usuario = ? ";
             try (PreparedStatement stmt = conexion.prepareStatement(query)) {
                 stmt.setString(1, usuario);
                 ResultSet rs = stmt.executeQuery();
                 if (rs.next()) {
                     String contraseñaEncriptadaBD = rs.getString("password");

                     if (BCrypt.verifyer().verify(contraseña.toCharArray(), contraseñaEncriptadaBD).verified) {
                         // Login exitoso - reiniciar contadores
                         IntentosFallidos = 0;
                         UsuarioTemporalBloqueado = null;

                         IDUsuario = rs.getInt("id");
                         NivelAcceso = rs.getInt("nivelPermiso");

                         switch (NivelAcceso) {
                             case 1 -> AbrirPanelAdministrativo();
                             case 2 -> AbrirGuiPrincipal();
                             default -> {
                                 JOptionPane.showMessageDialog(null, "Tu cuenta ha sido bloqueada, contacta al administrador", "Bloqueo", JOptionPane.ERROR_MESSAGE);
                                 LimpiarLogin();
                                 return;
                             }
                         }

                      
                         

                         JOptionPane.showMessageDialog(this, "Bienvenido, " + usuario + "!");
                         AuditoriaAsistencia();

                     } else {
                         // Contraseña incorrecta
                         IntentosFallidos++;
                         JOptionPane.showMessageDialog(this, "Contraseña incorrecta", "Error", JOptionPane.ERROR_MESSAGE);

                         // Verificar si es el mismo usuario que falló antes
                         if(UsuarioTemporalBloqueado == null || !usuario.equals(UsuarioTemporalBloqueado)) {
                             // Nuevo usuario fallando, reiniciar contador
                             IntentosFallidos = 1;
                             UsuarioTemporalBloqueado = usuario;
                         }

                         // Bloquear después de 3 intentos
                         if(IntentosFallidos >= 3 && usuario.equals(UsuarioTemporalBloqueado)) {
                             IDUsuario = rs.getInt("id");
                             UsuarioBloqueado = usuario;
                             JOptionPane.showMessageDialog(null, "Límite de intentos alcanzado. Usuario: " + usuario + " bloqueado por 3 minutos.", "Error", JOptionPane.ERROR_MESSAGE);
                             AuditoriaFallos();

                             // Temporizador de desbloqueo
                             Timer timer = new Timer(180000, e -> { // 180000 ms = 3 minutos
                                 UsuarioBloqueado = null;
                                 UsuarioTemporalBloqueado = null;
                                 IntentosFallidos = 0;
                             });
                             timer.setRepeats(false);
                             timer.start();
                         } 
                      
                     }
                 } else {
                     // Usuario no encontrado
                     IntentosFallidos++;
                     JOptionPane.showMessageDialog(this, "Usuario no encontrado", "Error", JOptionPane.ERROR_MESSAGE);

                     if(UsuarioTemporalBloqueado == null || !usuario.equals(UsuarioTemporalBloqueado)) {
                         IntentosFallidos = 1;
                         UsuarioTemporalBloqueado = usuario;
                     }

                     if(IntentosFallidos >= 3 && usuario.equals(UsuarioTemporalBloqueado)) {
                         UsuarioBloqueado = usuario;
                         JOptionPane.showMessageDialog(null, "Límite de intentos alcanzado. Usuario: " + usuario + " bloqueado por 3 minutos.", "Error", JOptionPane.ERROR_MESSAGE);

                         Timer timer = new Timer(180000, e -> {
                             UsuarioBloqueado = null;
                             UsuarioTemporalBloqueado = null;
                             IntentosFallidos = 0;
                         });
                         timer.setRepeats(false);
                         timer.start();
                     }
                 }
             } catch (SQLException ex) {
                 JOptionPane.showMessageDialog(this, "Error al validar credenciales: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
             }
         }
    
