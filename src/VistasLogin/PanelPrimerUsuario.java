    private void BotonCrearCuentaMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_BotonCrearCuentaMousePressed
        VerificacionCorreo = false;
        try {
            // Extraemos los datos que ha inresado el usuario para el ´primer usuario de la plataforma
            while(!Verificacion){
            PrimerUsuario = CampoNuevoUsuario.getText();
            if(PrimerUsuario == null || PrimerUsuario.trim().isEmpty())
            {
            JOptionPane.showMessageDialog(null, "Debe ingresar el campo de usuario", "Error", JOptionPane.ERROR_MESSAGE);
            continue;
            }
            Correo = CampoCorreo.getText();
            Dominio = (String) DominiosElectronicos.getSelectedItem();
            if(Correo == null || Correo.trim().isEmpty())
            {
            JOptionPane.showMessageDialog(null, "Debe ingresar el campo de correo", "Error", JOptionPane.ERROR_MESSAGE);
            continue;
            }
            CorreoElectronico = Correo + Dominio;

            VerificarCorreo(CorreoElectronico);

            P1 = new String(Password1.getPassword());
            P2 = new String(Password2.getPassword());

            if(P2.trim().isEmpty() || P1 == null || P1.trim().isEmpty() || P2 == null){
            JOptionPane.showMessageDialog(null,"Debe ingresar ambos campos antes de proceder");
            continue;
            }

            if(P1.equals(P2)& P2.equals(P1)){
            PasswordCrypt = BCrypt.withDefaults().hashToString(12, P2.toCharArray());
            }
            else{
            JOptionPane.showMessageDialog(null,"Las contraseñas no coinciden, intentalo de nuevo");
            continue;
            }
            Verificacion = true;}


            Acceso = 1;

            // Consulta SQL correcta con marcadores de parámetros
            String sql = "INSERT INTO usuarios (Usuario, Correo_Electronico, VerificacionCorreo, Password, nivelPermiso)"+
            " values (?,?,?,?,?)";


            // Preparar el statement
            PreparedStatement ps = conexion.prepareStatement(sql);

            // Asignar valores a los marcadores de parámetros

            ps.setString(1, PrimerUsuario);
            ps.setString(2, CorreoElectronico);
            ps.setString(3, VerificacionCorreo.toString());
            ps.setString(4, PasswordCrypt);
            ps.setInt(5, Acceso);

            // Ejecutar la inserción
            int filasInsertadas = ps.executeUpdate();
            if (filasInsertadas > 0) {
            JOptionPane.showMessageDialog(null,"Registro finalizado satisfactoriamente");
            AbrirLogin();
            }
                    } catch (SQLException ex) {
                        Logger.getLogger(PanelPrimerUsuario.class.getName()).log(Level.SEVERE, null, ex);
                    }

    }//GEN-LAST:event_BotonCrearCuentaMousePressed

